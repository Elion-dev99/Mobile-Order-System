async function stripe(path, params = {}, method = 'POST') {
  const url = `https://api.stripe.com/v1/${path}`;
  if (dryRun) {
    console.log(`[dry-run] ${method} ${path}`);
    if (path === 'payment_links') {
      return { id: 'dry_pl', url: `https://buy.stripe.com/test_dry_${Date.now()}` };
    }
    if (path.startsWith('webhook_endpoints') && method === 'POST') {
      return { id: 'we_dry', secret: 'whsec_dry_run_not_real' };
    }
    return { id: `dry_${path.replace(/\//g, '_')}`, data: [] };
  }
  const opts = {
    method,
    headers: { authorization: `Bearer ${KEY}` },
  };
  if (method !== 'GET') {
    const body = params instanceof URLSearchParams ? params : new URLSearchParams(params);
    opts.headers['content-type'] = 'application/x-www-form-urlencoded';
    opts.body = body;
  }
  const res = await fetch(url, opts);
  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    const msg = data?.error?.message || res.statusText;
    throw new Error(`${path}: ${msg}`);
  }
  return data;
}

function yenAmount(n) {
  return Math.round(Number(n) || 0);
}

function escJs(s) {
  return String(s || '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function writeGeneratedFile(linksByCycle, meta = {}) {
  const lines = Object.entries(linksByCycle).map(([planId, cycles]) => {
    const monthly = escJs(cycles.monthly);
    const annual = escJs(cycles.annual);
    return `  ${planId}: { monthly: '${monthly}', annual: '${annual}' },`;
  });
  const flat = Object.entries(linksByCycle).map(([planId, cycles]) => {
    const u = escJs(cycles.monthly || cycles.annual || '');
    return `  ${planId}: '${u}',`;
  });
  const content = `/**
 * Auto-generated by scripts/stripe-bootstrap.mjs — do not edit by hand.
 * Regenerate: STRIPE_SECRET_KEY=sk_test_... node scripts/stripe-bootstrap.mjs --write-generated
 */
export const STRIPE_PAYMENT_LINKS_BY_CYCLE = {
${lines.join('\n')}
};

/** Flat aliases (monthly link) for legacy stripePaymentLinks */
export const STRIPE_PAYMENT_LINKS_FLAT = {
${flat.join('\n')}
};

export const STRIPE_BOOTSTRAP_META = {
  generatedAt: '${meta.generatedAt || new Date().toISOString()}',
  webhookEndpointId: ${meta.webhookEndpointId ? `'${escJs(meta.webhookEndpointId)}'` : 'null'},
};
`;
  fs.writeFileSync(GENERATED, content, 'utf8');
  console.log(`Wrote ${GENERATED}`);
}

async function ensureCoupon(planId, amountOff) {
  const id = commerce.couponIds?.[planId] || `QO_${planId.toUpperCase()}_INTRO`;
  if (dryRun) return { id };
  try {
    return await stripe(`coupons/${encodeURIComponent(id)}`, {}, 'GET');
  } catch {
    const p = new URLSearchParams();
    p.set('id', id);
    p.set('currency', 'jpy');
    p.set('amount_off', String(yenAmount(amountOff)));
    p.set('duration', 'once');
    p.set('name', `QuickOrder ${planId} 初月サブスク値引き`);
    p.set('metadata[planId]', planId);
    return stripe('coupons', p);
  }
}

async function createProduct(plan) {
  const p = new URLSearchParams();
  p.set('name', `QuickOrder ${plan.name}`);
  p.set('description', plan.tagline || '');
  p.set('metadata[planId]', plan.id);
  return stripe('products', p);
}

async function createPrice({ productId, unitAmount, recurring }) {
  const p = new URLSearchParams();
  p.set('product', productId);
  p.set('currency', 'jpy');
  p.set('unit_amount', String(yenAmount(unitAmount)));
  if (recurring) {
    p.set('recurring[interval]', recurring.interval);
    if (recurring.interval_count) p.set('recurring[interval_count]', String(recurring.interval_count));
  }
  return stripe('prices', p);
}

