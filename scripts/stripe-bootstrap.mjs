async function bootstrapPlan(plan) {
  const introOff = Number(commerce.introFirstMonthOff?.[plan.id] || 0);
  const annualTotal = yenAmount(plan.priceMonthly * PRODUCT.annualMultiplier);

  console.log(`\n=== ${plan.id} (${plan.name}) ===`);
  console.log(`  初期 ¥${plan.priceSetup} · 月額 ¥${plan.priceMonthly} · 年額 ¥${annualTotal} · 初月値引き ¥${introOff}`);

  const product = await createProduct(plan);
  const setupPrice = await createPrice({ productId: product.id, unitAmount: plan.priceSetup });
  const monthlyPrice = await createPrice({
    productId: product.id,
    unitAmount: plan.priceMonthly,
    recurring: { interval: 'month' },
  });
  const annualPrice = await createPrice({
    productId: product.id,
    unitAmount: annualTotal,
    recurring: { interval: 'year' },
  });

  let coupon = null;
  if (introOff > 0) coupon = await ensureCoupon(plan.id, introOff);

  const monthlyLink = await createPaymentLink({
    planId: plan.id,
    cycle: 'monthly',
    setupPriceId: setupPrice.id,
    subPriceId: monthlyPrice.id,
    couponId: coupon?.id,
  });
  const annualLink = await createPaymentLink({
    planId: plan.id,
    cycle: 'annual',
    setupPriceId: setupPrice.id,
    subPriceId: annualPrice.id,
    couponId: null,
  });

  return {
    planId: plan.id,
    monthly: monthlyLink.url,
    annual: annualLink.url,
  };
}

async function ensureWebhookEndpoint() {
  const list = await stripe('webhook_endpoints?limit=100', {}, 'GET');
  const existing = (list.data || []).find((w) => w.url === WEBHOOK_URL && !w.disabled);
  if (existing) {
    console.log(`Webhook already registered: ${existing.id} (signing secret is only shown at creation — use Dashboard or repo secret STRIPE_WEBHOOK_SECRET)`);
    return { id: existing.id, secret: process.env.STRIPE_WEBHOOK_SECRET || null, existing: true };
  }
  const p = new URLSearchParams();
  p.set('url', WEBHOOK_URL);
  p.set('description', 'QuickOrder Cloudflare Pages (prep)');
  p.set('enabled_events[0]', 'checkout.session.completed');
  p.set('enabled_events[1]', 'checkout.session.async_payment_succeeded');
  const ep = await stripe('webhook_endpoints', p);
  console.log(`Created webhook ${ep.id} → ${WEBHOOK_URL}`);
  return { id: ep.id, secret: ep.secret, existing: false };
}

async function main() {
  let linksByCycle = {};
  let webhookMeta = { webhookEndpointId: null };

  if (!registerWebhook || !onlyPlan) {
    const plans = PLANS.filter((p) => !onlyPlan || p.id === onlyPlan);
    if (!plans.length) {
      console.error('No plans matched', onlyPlan);
      process.exit(1);
    }
    for (const plan of plans) {
      const row = await bootstrapPlan(plan);
      linksByCycle[row.planId] = { monthly: row.monthly, annual: row.annual };
    }
    console.log('\n--- stripePaymentLinksByCycle ---\n');
    console.log(JSON.stringify(linksByCycle, null, 2));
  }

  if (registerWebhook) {
    const wh = await ensureWebhookEndpoint();
    webhookMeta.webhookEndpointId = wh.id;
    if (wh.secret) {
      const outPath = path.join(ROOT, '.stripe-webhook-secret');
      fs.writeFileSync(outPath, wh.secret, 'utf8');
      console.log(`Webhook signing secret written to ${outPath} (upload to Cloudflare STRIPE_WEBHOOK_SECRET)`);
      if (process.env.GITHUB_OUTPUT) {
        fs.appendFileSync(process.env.GITHUB_OUTPUT, `webhook_secret=${wh.secret}\n`);
      }
    }
  }

  if (writeGenerated && Object.keys(linksByCycle).length) {
    writeGeneratedFile(linksByCycle, {
      generatedAt: new Date().toISOString(),
      webhookEndpointId: webhookMeta.webhookEndpointId,
    });
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
